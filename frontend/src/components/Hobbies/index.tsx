const ALL = "All";

/** Two full rows at the widest breakpoint — see --cols in index.css. */
const PAGE_SIZE = 10;

/** One open gallery — the photo wall brings its EXIF rail, ceramics doesn't. */
type Gallery = {
  images: ViewerImage[];
  index: number;
  showMeta: boolean;
};

const Hobbies = () => {
  const [filter, setFilter] = useState(ALL);
  const [page, setPage] = useState(0);
  const [gallery, setGallery] = useState<Gallery | null>(null);
  const closeViewer = useCallback(() => setGallery(null), []);
  const setIndex = useCallback(
    (index: number) => setGallery((g) => (g ? { ...g, index } : g)),
    []
  );

  // Chips come from the photos themselves — adding a frame in a new set needs no
  // second edit here. Fullest set first, ties alphabetical, so the row reads as
  // ordered rather than arbitrary.
  const sets = useMemo(() => {
    const counts = new Map<string, number>();
    photos.forEach((p) => counts.set(p.category, (counts.get(p.category) ?? 0) + 1));
    const ordered = [...counts]
      .map(([name, count]) => ({ name, count }))
      .sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));
    return [{ name: ALL, count: photos.length }, ...ordered];
  }, []);

  const matching = useMemo(
    () => (filter === ALL ? photos : photos.filter((p) => p.category === filter)),
    [filter]
  );

  // Paged so the wall stays two rows tall however many frames get added, rather
  // than growing the section a row at a time.
  const pageCount = Math.max(1, Math.ceil(matching.length / PAGE_SIZE));
  const current = Math.min(page, pageCount - 1);
  const shown = matching.slice(current * PAGE_SIZE, current * PAGE_SIZE + PAGE_SIZE);

  const pick = (name: string) => {
    setFilter(name);
    setPage(0);
    setGallery(null);
  };

  const goToPage = (next: number) => {
    setPage(next);
    setGallery(null);
  };

  // The wall loads 760px thumbs; the viewer pulls the full-size frame. Paging is
  // a layout device for the wall only — the viewer gets the whole filtered set,
  // so the arrows walk every matching frame instead of stopping at a page edge.
  // `i` is the tile's position on the page, hence the offset.
  const openPhoto = (i: number) =>
    setGallery({
      showMeta: true,
      index: current * PAGE_SIZE + i,
      images: matching.map((p) => ({
        src: `/photos/${p.file}.webp`,
        alt: p.alt,
        caption: p.title,
        meta: [{ label: "Set", value: p.category }, ...(p.meta ?? [])],
      })),
    });

  const openCeramics = () =>
    setGallery({
      showMeta: false,
      index: 0,
      images: ceramics.map((c) => ({
        src: `/photos/${c.file}.webp`,
        alt: c.alt,
        caption: c.title,
      })),
    });

  return (
    <div className="hobbies">
      <p className="hob-lead">
        When I'm not behind a keyboard I have a few other hobbies! I like to get outside and take photos of cool things I see Here are a few of my favorites.
      </p>

      <section className="hob-sub" aria-labelledby="hob-photography">
        <h3 className="hob-sub-title" id="hob-photography">Photography</h3>

        <div className="hob-filters" role="group" aria-label="Filter photos by set">
          {sets.map(({ name, count }) => (
            <button
              key={name}
              type="button"
              className={`hob-filter ${filter === name ? "active" : ""}`}
              aria-pressed={filter === name}
              onClick={() => pick(name)}
            >
              {name}
              <span className="hob-filter-count">{count}</span>
            </button>
          ))}
        </div>

        <div className="hob-wall">
          {shown.map((photo, i) => (
            <button
              key={photo.file}
              type="button"
              className="hob-shot"
              onClick={() => openPhoto(i)}
            >
              <img
                src={`/photos/${photo.file}-thumb.webp`}
                alt={photo.alt}
                style={photo.focus ? { objectPosition: photo.focus } : undefined}
                loading="lazy"
                decoding="async"
                draggable={false}
              />
              <span className="hob-shot-label">
                <span className="hob-shot-title">{photo.title}</span>
                <span className="hob-shot-set">{photo.category}</span>
              </span>
            </button>
          ))}
        </div>

        {pageCount > 1 && (
          <nav className="hob-pager" aria-label="Photo pages">
            <button
              type="button"
              className="hob-page-arrow"
              onClick={() => goToPage(current - 1)}
              disabled={current === 0}
              aria-label="Previous page"
            >
              <FiChevronLeft />
            </button>

            {Array.from({ length: pageCount }, (_, i) => (
              <button
                key={i}
                type="button"
                className={`hob-page ${i === current ? "active" : ""}`}
                aria-label={`Page ${i + 1} of ${pageCount}`}
                aria-current={i === current ? "true" : undefined}
                onClick={() => goToPage(i)}
              >
                {i + 1}
              </button>
            ))}

            <button
              type="button"
              className="hob-page-arrow"
              onClick={() => goToPage(current + 1)}
              disabled={current === pageCount - 1}
              aria-label="Next page"
            >
              <FiChevronRight />
            </button>
          </nav>
        )}

        <p className="hob-notes">
          <span className="hob-note">
            <FiCamera aria-hidden="true" />
            Most came off a Nikon D5600, the rest an iPhone.
          </span>
          <span className="hob-note">
            <TbPencilOff aria-hidden="true" />
            None were edited.
          </span>
        </p>
      </section>

      {/* Ceramics and Guitar share one row: the stack leaves a lot of empty
          space to its right, so the guitar blurb moves up into it. The two
          sections go `display: contents` on wide screens so their headings,
          leads and bodies land on shared grid rows and line up. */}
      <div className="hob-split">
        <section className="hob-sub" aria-labelledby="hob-ceramics">
          <h3 className="hob-sub-title" id="hob-ceramics">Ceramics</h3>
          <p className="hob-sub-lead">An interest of mine I've had for a while.</p>

          {/* One button, not a gallery — the fan behind the front piece is
              decorative, so only the front image carries alt text. */}
          <button type="button" className="cer-stack" onClick={openCeramics}>
            {ceramics.slice(1, 4).map((piece, i) => (
              <span key={piece.file} className={`cer-card cer-back cer-back-${i + 1}`}>
                <img
                  src={`/photos/${piece.file}-thumb.webp`}
                  alt=""
                  loading="lazy"
                  decoding="async"
                  draggable={false}
                />
              </span>
            ))}

            <span className="cer-card cer-front">
              <img
                src={`/photos/${ceramics[0].file}-thumb.webp`}
                alt={ceramics[0].alt}
                loading="lazy"
                decoding="async"
                draggable={false}
              />
              <span className="cer-cue">
                <FiLayers aria-hidden="true" />
                See all {ceramics.length}
              </span>
            </span>
          </button>
        </section>

        <section className="hob-sub" aria-labelledby="hob-guitar">
          <h3 className="hob-sub-title" id="hob-guitar">Guitar</h3>
          <p className="hob-sub-lead">Self-taught little by little.</p>
          {/* One grid item, two beats: the split's row-3 placement targets the
              stack, so the sentences can't land in the same cell. */}
          <div className="hob-blurb-stack">
            <p className="hob-blurb">
              I've been playing acoustic guitar for the last <span className="hl">~3</span> years.
            </p>
            <p className="hob-blurb">
              I have a long way to go but that's part of the fun.
            </p>
          </div>
        </section>
      </div>

      {gallery && gallery.images[gallery.index] && (
        <ImageViewer
          images={gallery.images}
          index={gallery.index}
          onIndex={setIndex}
          onClose={closeViewer}
          showMeta={gallery.showMeta}
        />
      )}
    </div>
  );
};

export default Hobbies;
